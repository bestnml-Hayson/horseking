def _extract_body_text(html_text):
    html_text = html_text or ""
    body = _re.search(r"<body[^>]*>(.*)</body\s*>", html_text, _re.DOTALL | _re.IGNORECASE)
    src = body.group(1) if body else html_text
    src = _re.sub(r"<script[^>]*>.*?</script\s*>", "", src, flags=_re.DOTALL | _re.IGNORECASE)
    src = _re.sub(r"<style[^>]*>.*?</style\s*>", "", src, flags=_re.DOTALL | _re.IGNORECASE)
    src = _re.sub(r"<br\s*/?>", "\t", src, flags=_re.IGNORECASE)
    src = _re.sub(r"</tr\s*>", "\n", src, flags=_re.IGNORECASE)
    src = _re.sub(r"</td\s*>", "\t", src, flags=_re.IGNORECASE)
    src = _re.sub(r"<[^>]+>", "", src)
    src = _re.sub(r"[ \t]+", "\t", src)
    return src


