$codeLines += '        $res.OutputStream.Close()'
$codeLines += '    } catch {'
$codeLines += '        $errTxt = $_.Exception.Message'
$codeLines += '        $errMsg = "ERROR: " + $errTxt'
$codeLines += '        Write-Host $errMsg -ForegroundColor Red'
$codeLines += '        try {'
