$codeLines += 'WriteBanner'
$codeLines += '$script:refreshRunning = $false'
$codeLines += '$script:lastRefreshResult = $null'
$codeLines += '$handlerPath = Join-Path $PSScriptRoot "api_refresh_handler.ps1"'
$codeLines += '$mimeHtml = "text/html; charset=utf-8"'
$codeLines += '$mimeJs = "application/javascript; charset=utf-8"'
$codeLines += '$mimeCss = "text/css; charset=utf-8"'
$codeLines += '$mimeJson = "application/json; charset=utf-8"'
$codeLines += '$mimePng = "image/png"'
$codeLines += '$mimeJpg = "image/jpeg"'
$codeLines += '$mimeSvg = "image/svg+xml"'
$codeLines += '$mimeCsv = "text/csv; charset=utf-8"'
$codeLines += '$mimeIco = "image/x-icon"'
$codeLines += '$mimeOct = "application/octet-stream"'
$codeLines += 'function GetCType([string]$ext) {'
$codeLines += '    if ($ext -eq ".html") { return $mimeHtml }'
$codeLines += '    if ($ext -eq ".js") { return $mimeJs }'
$codeLines += '    if ($ext -eq ".css") { return $mimeCss }'
$codeLines += '    if ($ext -eq ".json") { return $mimeJson }'
$codeLines += '    if ($ext -eq ".png") { return $mimePng }'
$codeLines += '    if ($ext -eq ".jpg") { return $mimeJpg }'
$codeLines += '    if ($ext -eq ".svg") { return $mimeSvg }'
$codeLines += '    if ($ext -eq ".csv") { return $mimeCsv }'
$codeLines += '    if ($ext -eq ".ico") { return $mimeIco }'
$codeLines += '    return $mimeOct'
$codeLines += '}'
$codeLines += 'function ResolveApiPath([string]$path) {'
$codeLines += '    $hp = "/api/history/"'
$codeLines += '    $pp = "/api/profiles/"'
$codeLines += '    $sp = "/api/stats/"'
$codeLines += '    $rp = "/api/references/"'
$codeLines += '    $tp = "/api/trackwork/"'
$codeLines += '    if ($path.StartsWith($hp)) {'
$codeLines += '        $fn = $path.Substring($hp.Length)'
$codeLines += '        $p1 = Join-Path $dataDir ("history\" + $fn)'
$codeLines += '        if (Test-Path $p1 -PathType Leaf) { return $p1 }'
$codeLines += '        $p2 = Join-Path $publicDir ("data\history\" + $fn)'
$codeLines += '        if (Test-Path $p2 -PathType Leaf) { return $p2 }'
$codeLines += '        return $null'
$codeLines += '    }'
$codeLines += '    if ($path -eq "/api/profiles/horses" -or $path -eq "/api/profiles/horses/") {'
$codeLines += '        $p1 = Join-Path $dataDir "profiles\horses_db.json"'
$codeLines += '        if (Test-Path $p1 -PathType Leaf) { return $p1 }'
$codeLines += '        $p2 = Join-Path $publicDir "data\profiles\horses_db.json"'
$codeLines += '        if (Test-Path $p2 -PathType Leaf) { return $p2 }'
$codeLines += '        return $null'
$codeLines += '    }'
$codeLines += '    if ($path.StartsWith($pp)) {'
$codeLines += '        $fn = $path.Substring($pp.Length)'
$codeLines += '        if ([string]::IsNullOrWhiteSpace($fn)) { $fn = "horses_db.json" }'
$codeLines += '        $p1 = Join-Path $dataDir ("profiles\" + $fn)'
$codeLines += '        if (Test-Path $p1 -PathType Leaf) { return $p1 }'
$codeLines += '        $p2 = Join-Path $publicDir ("data\profiles\" + $fn)'
$codeLines += '        if (Test-Path $p2 -PathType Leaf) { return $p2 }'
$codeLines += '        return $null'
$codeLines += '    }'
$codeLines += '    if ($path.StartsWith($sp)) {'
$codeLines += '        $fn = $path.Substring($sp.Length)'
$codeLines += '        $p1 = Join-Path $dataDir ("stats\" + $fn)'
$codeLines += '        if (Test-Path $p1 -PathType Leaf) { return $p1 }'
$codeLines += '        $p2 = Join-Path $publicDir ("data\stats\" + $fn)'
$codeLines += '        if (Test-Path $p2 -PathType Leaf) { return $p2 }'
$codeLines += '        return $null'
$codeLines += '    }'
$codeLines += '    if ($path.StartsWith($rp)) {'
$codeLines += '        $fn = $path.Substring($rp.Length)'
$codeLines += '        $p1 = Join-Path $dataDir ("references\" + $fn)'
$codeLines += '        if (Test-Path $p1 -PathType Leaf) { return $p1 }'
$codeLines += '        $p2 = Join-Path $publicDir ("data\references\" + $fn)'
$codeLines += '        if (Test-Path $p2 -PathType Leaf) { return $p2 }'
$codeLines += '        return $null'
$codeLines += '    }'
$codeLines += '    if ($path.StartsWith($tp)) {'
$codeLines += '        $fn = $path.Substring($tp.Length)'
$codeLines += '        $p1 = Join-Path $dataDir ("trackwork\" + $fn)'
$codeLines += '        if (Test-Path $p1 -PathType Leaf) { return $p1 }'
$codeLines += '        $p2 = Join-Path $publicDir ("data\trackwork\" + $fn)'
$codeLines += '        if (Test-Path $p2 -PathType Leaf) { return $p2 }'
$codeLines += '        return $null'
$codeLines += '    }'
$codeLines += '    if ($path -eq "/api/races" -or $path -eq "/api/races/" -or $path -eq "/api/list") {'
$codeLines += '        $hist = Join-Path $publicDir "data\history"'
$codeLines += '        if (Test-Path $hist) {'
$codeLines += '            $files = Get-ChildItem $hist -Filter "*.json" | Sort-Object Name'
$codeLines += '            $list = @()'
$codeLines += '            foreach ($f in $files) { $list += $f.Name }'
$codeLines += '            return ,@($list,$true)'
$codeLines += '        }'
$codeLines += '        return $null'
$codeLines += '    }'
$codeLines += '    return $null'
$codeLines += '}'
$codeLines += 'function SendJson($Response, $Object, [int]$Depth) {'
$codeLines += '    $jsonBody = ConvertTo-Json $Object -Depth $Depth -Compress'
$codeLines += '    $bytes = $utf8NoBom.GetBytes($jsonBody)'
$codeLines += '    $Response.ContentType = $mimeJson'
$codeLines += '    $Response.ContentLength64 = $bytes.Length'
$codeLines += '    $Response.AddHeader("Cache-Control", "no-cache")'
$codeLines += '    $Response.AddHeader("Access-Control-Allow-Origin", "*")'
$codeLines += '    $Response.OutputStream.Write($bytes, 0, $bytes.Length)'
$codeLines += '    return $bytes.Length'
$codeLines += '}'
$codeLines += 'while ($listener.IsListening) {'
$codeLines += '    try {'
$codeLines += '        $ctx = $listener.GetContext()'
$codeLines += '        $req = $ctx.Request'
$codeLines += '        $res = $ctx.Response'
$codeLines += '        $path = [System.Web.HttpUtility]::UrlDecode($req.Url.AbsolutePath)'
$codeLines += '        if ($path -eq "/") { $path = "/index.html" }'
$codeLines += '        $clientIP = $req.RemoteEndPoint.Address.ToString()'
$codeLines += '        $stamp = Get-Date -Format HH:mm:ss'
$codeLines += '        if ($path -eq "/api/refresh" -or $path -eq "/api/refresh/") {'
$codeLines += '            try {'
$codeLines += '                if ($script:refreshRunning) {'
$codeLines += '                    $busyObj = New-Object PSObject'
$codeLines += '                    $busyObj | Add-Member NoteProperty ok $false'
