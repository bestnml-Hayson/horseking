$codeLines += '            [void]$sb.Append("] EXCEPTION: ")'
$codeLines += '            [void]$sb.Append($errTxt)'
$codeLines += '            [void]$sb.Append($nl)'
$codeLines += '            $logLine = $sb.ToString()'
$codeLines += '            [IO.File]::AppendAllText($logFile, $logLine, $utf8NoBom)'
$codeLines += '        } catch {}'
$codeLines += '    }'
$codeLines += '}'
