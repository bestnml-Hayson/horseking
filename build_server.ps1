$codeLines += '                Write-Host $failLine -ForegroundColor Red'
$codeLines += '                $res.OutputStream.Close()'
$codeLines += '                continue'
$codeLines += '            }'
$codeLines += '        }'
$codeLines += '        $resolved = ResolveApiPath $path'
$codeLines += '        $file = $null'
$codeLines += '        $isApiList = $false'
$codeLines += '        if ($resolved -is [array] -and $resolved.Count -ge 2 -and $resolved[1] -eq $true) {'
$codeLines += '            $isApiList = $true'
$codeLines += '            $blen = SendJson -Response $res -Object $resolved[0] -Depth 3'
$codeLines += '            $szStr = $blen.ToString() + " bytes"'
$codeLines += '            $apiLine = "[" + $stamp + "] " + $clientIP + "  200 API  " + $path + " [" + $szStr + "]"'
$codeLines += '            Write-Host $apiLine -ForegroundColor Green'
$codeLines += '            $res.OutputStream.Close()'
$codeLines += '            continue'
$codeLines += '        } elseif ($resolved) {'
$codeLines += '            $file = $resolved'
$codeLines += '        } else {'
$codeLines += '            $file = Join-Path $publicDir $path.TrimStart("/")'
$codeLines += '        }'
$codeLines += '        if ($file -and (Test-Path $file -PathType Leaf)) {'
$codeLines += '            $ext = [System.IO.Path]::GetExtension($file).ToLower()'
$codeLines += '            $ctype = GetCType $ext'
$codeLines += '            $bytes = [System.IO.File]::ReadAllBytes($file)'
$codeLines += '            $res.ContentType = $ctype'
$codeLines += '            $res.ContentLength64 = $bytes.Length'
$codeLines += '            $res.AddHeader("Cache-Control", "no-cache")'
$codeLines += '            $res.AddHeader("Access-Control-Allow-Origin", "*")'
$codeLines += '            $res.OutputStream.Write($bytes, 0, $bytes.Length)'
$codeLines += '            $isJson = $false'
$codeLines += '            if ($ext -eq ".json") { $isJson = $true }'
$codeLines += '            if ($resolved) { $isJson = $true }'
$codeLines += '            $okLine = "[" + $stamp + "] " + $clientIP + "  200 OK   " + $path'
