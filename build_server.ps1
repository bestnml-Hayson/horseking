$codeLines += '                        $outObj | Add-Member NoteProperty raw $snippet'
$codeLines += '                    }'
$codeLines += '                }'
$codeLines += '                $script:lastRefreshResult = $outObj'
$codeLines += '                $script:refreshRunning = $false'
$codeLines += '                [void](SendJson -Response $res -Object $outObj -Depth 10)'
