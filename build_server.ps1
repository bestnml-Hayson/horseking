$codeLines += '                    $okProp = $outObj | Select-Object -ExpandProperty ok -ErrorAction Stop'
$codeLines += '                    if ($okProp -eq $true) { $isOk = $true }'
$codeLines += '                } catch { $isOk = $false }'
$codeLines += '                if ($isOk) { $logColor = [ConsoleColor]::Green } else { $logColor = [ConsoleColor]::Red }'
$codeLines += '                $durDisp = "n/a"'
$codeLines += '                try {'
$codeLines += '                    $durProp = $outObj | Select-Object -ExpandProperty duration_sec -ErrorAction Stop'
$codeLines += '                    $durDisp = $durProp.ToString() + " sec"'
$codeLines += '                } catch {}'
$codeLines += '                $st2 = Get-Date -Format HH:mm:ss'
$codeLines += '                $doneLine = "[" + $st2 + "] " + $clientIP + "  DONE    /api/refresh [" + $durDisp + "]"'
$codeLines += '                Write-Host $doneLine -ForegroundColor $logColor'
$codeLines += '                $res.OutputStream.Close()'
