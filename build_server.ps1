$codeLines += '                    continue'
$codeLines += '                }'
$codeLines += '                $script:refreshRunning = $true'
$codeLines += '                $startLine = "[" + $stamp + "] " + $clientIP + "  START   /api/refresh"'
$codeLines += '                Write-Host $startLine -ForegroundColor Cyan'
$codeLines += '                $handlerOut = & powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -File $handlerPath'
